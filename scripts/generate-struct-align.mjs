/**
 * Build struct property alignment map from JJKUAssetProcessor hardcoded schemas
 * (AbramsDataTable.hpp offsetof analysis).
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const jjkSchemas = pathToFileURL(
  "C:/Users/Ahmed/Documents/Apps/JJKUAssetProcessor/CookedDataTablePatcher/dist/hardcodedSchemas.generated.js",
).href;

const { HARDCODED_SCHEMAS } = await import(jjkSchemas);

const out = {};
for (const [structName, schema] of Object.entries(HARDCODED_SCHEMAS)) {
  const fields = {};
  for (const col of schema.columns ?? []) {
    if (typeof col.align === "number") fields[col.name] = col.align;
  }
  if (Object.keys(fields).length > 0) out[structName] = fields;
}

const target = path.resolve("src/unversioned/structPropertyAlign.generated.ts");
const body = `/** Generated by scripts/generate-struct-align.mjs — do not edit. */
export const STRUCT_PROPERTY_ALIGN: Readonly<Record<string, Readonly<Record<string, number>>>> = ${JSON.stringify(out, null, 2)} as const;

export function getStructPropertyAlign(structName: string, propertyName: string): number | undefined {
  return STRUCT_PROPERTY_ALIGN[structName]?.[propertyName];
}
`;
fs.writeFileSync(target, body);
console.log(`Wrote ${target} (${Object.keys(out).length} structs)`);
